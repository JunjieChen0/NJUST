#!/usr/bin/env node

/**
 * Generate the complete VS Code settings schema from src/package.json.
 *
 * The extension manifest remains the single source of truth for defaults and
 * bounds. This generator derives a Zod schema + typed accessor used at runtime,
 * eliminating silent drift between contributed settings and consumers.
 *
 * Usage:
 *   node scripts/generate-settings-schema.mjs          # write the schema
 *   node scripts/generate-settings-schema.mjs --check  # fail if out of date
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const manifestPath = resolve(rootDir, "src/package.json")
const outputPath = resolve(rootDir, "packages/types/src/extension-settings.ts")
const checkOnly = process.argv.includes("--check")

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"))
const properties = manifest.contributes?.configuration?.properties
if (!properties || typeof properties !== "object") {
	throw new Error("src/package.json has no contributes.configuration.properties")
}

function schemaFor(property) {
	let schema
	switch (property.type) {
		case "boolean":
			schema = "z.boolean()"
			break
		case "number":
		case "integer":
			schema = property.type === "integer" ? "z.number().int()" : "z.number()"
			if (typeof property.minimum === "number") schema += `.min(${property.minimum})`
			if (typeof property.maximum === "number") schema += `.max(${property.maximum})`
			break
		case "string":
			schema = Array.isArray(property.enum) ? `z.enum(${JSON.stringify(property.enum)})` : "z.string()"
			break
		case "array": {
			const itemType = property.items?.type
			const itemSchema =
				itemType === "string" ? "z.string()" : itemType === "number" ? "z.number()" : "z.unknown()"
			schema = `z.array(${itemSchema})`
			break
		}
		case "object":
			schema = "z.record(z.string(), z.unknown())"
			break
		default:
			schema = "z.unknown()"
	}
	return property.default === undefined
		? `${schema}.optional()`
		: `${schema}.default(${JSON.stringify(property.default)})`
}

const entries = Object.entries(properties)
	.filter(([key]) => key.startsWith("njust-ai."))
	.sort(([a], [b]) => a.localeCompare(b))

const body = entries
	.map(([key, property]) => {
		const shortKey = key.slice("njust-ai.".length)
		return `\t${JSON.stringify(shortKey)}: ${schemaFor(property)},`
	})
	.join("\n")

const output = `// AUTO-GENERATED by scripts/generate-settings-schema.mjs — DO NOT EDIT BY HAND.
// Source of truth: src/package.json contributes.configuration.properties.
import { z } from "zod"

export const extensionSettingSchemas = {
${body}
} as const

export type ExtensionSettingKey = keyof typeof extensionSettingSchemas
export type ExtensionSettingValue<K extends ExtensionSettingKey> = z.infer<(typeof extensionSettingSchemas)[K]>

/**
 * Parse a raw VS Code configuration value, falling back to the manifest default
 * when it is absent or has an invalid shape. This keeps malformed settings from
 * silently propagating through the extension.
 */
export function parseExtensionSetting<K extends ExtensionSettingKey>(
	key: K,
	value: unknown,
): ExtensionSettingValue<K> {
	const schema = extensionSettingSchemas[key] as z.ZodTypeAny
	const result = schema.safeParse(value)
	return (result.success ? result.data : schema.parse(undefined)) as ExtensionSettingValue<K>
}
`

if (checkOnly) {
	if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== output) {
		console.error("extension-settings.ts is out of date. Run: node scripts/generate-settings-schema.mjs")
		process.exit(1)
	}
	console.log(`Settings schema is up to date (${entries.length} settings).`)
} else {
	mkdirSync(dirname(outputPath), { recursive: true })
	writeFileSync(outputPath, output, "utf8")
	console.log(`Generated ${outputPath} (${entries.length} settings).`)
}
